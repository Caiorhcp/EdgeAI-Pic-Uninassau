def criar_dataset():
    os.makedirs("data/raw", exist_ok=True)
    registros = []
    for classe, textos in DADOS.items():
        for texto in textos:
            registros.append({"texto": texto, "classe": classe})

    caminho = "data/raw/dataset_juridico.json"
    with open(caminho, "w", encoding="utf-8") as f:
        json.dump(registros, f, ensure_ascii=False, indent=2)

    print(f"Dataset criado: {caminho}")
    print(f"Total de amostras: {len(registros)}")
    print("\nDistribuição por classe:")
    for classe, textos in DADOS.items():
        print(f"  {classe:10s}: {len(textos)} amostras")

if __name__ == "__main__":
    criar_dataset()